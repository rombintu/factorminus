@pytest.mark.parametrize("text", ADVICE)
def test_advice_is_caught(text):
    assert find_forbidden(text), text


@pytest.mark.parametrize("text", FACTS)
def test_facts_pass(text):
    assert find_forbidden(text) == [], text


def test_regression_size():
    assert len(ADVICE) + len(FACTS) >= 40
